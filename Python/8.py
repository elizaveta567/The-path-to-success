# Суммарные продажи
#
# Сложите продажи из двух словарей. Если товар есть в обоих, сложите его количества; если
# только в одном — возьмите его количество. Соберите и выведите новый словарь, не меняя
# исходные. Для двух пустых словарей результат — {}.
#
# Проверьте себя:
# {'кофе': 17, 'чай': 5, 'торт': 3}; два пустых словаря дают {}.

first = {'кофе': 10, 'чай': 5}
second = {'кофе': 7, 'торт': 3}

# Напишите решение ниже.

d = {}
for key, value in first.items():
    d[key]=value

for key, value in second.items():
    if key in d.keys():
        d[key]+=value
    else:
        d[key]=value
print(d)


#Эталонное решение
merged = first.copy()

for key, value in second.items():
    merged[key] = merged.get(key,0)+value

print(merged)



