# Удаление дублей с порядком
#
# Уберите повторы, сохранив порядок первого появления чисел. Идите слева направо и
# добавляйте число в новый список, только если его там ещё нет. Используйте not in, без
# множества. Выведите новый список; исходный не меняйте.
#
# Проверьте себя:
# Именно [3, 2, 1]; для [2, 2, 1, 2]: [2, 1]; для []: [].

values = [3, 2, 1, 3, 2]

# Напишите решение ниже.
def new_list(values):
    d = []
    for i in values:
        if i not in d:
            d.append(i)
    return d

print(new_list(values))





# Пользователи и ответы
#
# Каждый элемент responses — автор одного ответа. Один человек мог ответить несколько раз.
# Выведите количество разных авторов и их долю: количество авторов, делённое на общее
# количество ответов. Долю оставьте числом от 0 до 1, без перевода в проценты. Для пустого
# списка выведите 0 и 0.
#
# Проверьте себя:
# Количество: 3; доля: 0.6, потому что ответов 5. Для []: 0 и 0.

responses = ['u1', 'u2', 'u1', 'u3', 'u2']

# Напишите решение ниже.

def df(responses):
    d = len(set(responses))
    n = len(responses)
    if n==0:
        return 0
    else:
        return (n,d/n)

print(df(responses))