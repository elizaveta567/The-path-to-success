# Количество платежей
#
# Посчитайте и выведите, за сколько платежей получится погасить долг. Каждый платёж — не
# больше payment рублей, последний — только оставшийся долг. Используйте while и
# уменьшайте debt, пока он не станет равен нулю. Начальный долг неотрицательный, payment
# больше нуля.
#
# Проверьте себя:
# 23500, 3000 → 8 платежей; 0, 3000 → 0.

debt = 23500
payment = 3000
k = 0
# Напишите решение ниже.
while debt>0:
    if debt<payment:
        debt=0
    else:
        debt-=payment
    k+=1
print(k)