# Два способа развернуть список
#
# Получите и выведите две перевёрнутые копии списка: одну срезом, вторую циклом по
# индексам. Исходный список не меняйте.
#
# Проверьте себя:
# Дважды [4, 3, 2, 1]; для [] оба результата — [].

items = [1, 2, 3, 4]

# Напишите решение ниже.

